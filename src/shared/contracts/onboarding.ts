import { z } from "zod";
import { withSwagger } from "@/shared/nest/zod-swagger-metadata";

export const otherslikesSchema = withSwagger(
	z.record(
		withSwagger(z.string().array(), {
			description: "Free-form interest values for a custom category.",
			example: ["gardening", "birds"],
		}),
	),
	{
		description: "Map of custom interest categories to lists of values.",
		example: { hobbies: ["gardening", "birds"] },
	},
);

export const likesSchema = withSwagger(
	z.object({
		football: withSwagger(z.string().array(), {
			description: "Football-related interests.",
			example: ["Benfica", "Champions League"],
		}),
		music: withSwagger(z.string().array(), {
			description: "Music-related interests.",
			example: ["Fado", "Classical music"],
		}),
		cinema: withSwagger(z.string().array(), {
			description: "Cinema-related interests.",
			example: ["Classic films", "Comedies"],
		}),
		gastronomy: withSwagger(z.string().array(), {
			description: "Food-related interests.",
			example: ["Bacalhau", "Pastel de nata"],
		}),
		hobbies: withSwagger(z.string().array(), {
			description: "Free-form hobbies collected during onboarding.",
			example: ["jardim", "leitura", "netos"],
		}),
		others: otherslikesSchema,
	}),
	{
		description: "Preference groups associated with a senior.",
	},
);

export const onboardSeniorRequestSchema = withSwagger(
	z.object({
		email: withSwagger(z.string().email().optional(), {
			description:
				"Senior account email. If omitted a placeholder is generated by the backend.",
			example: "senior@example.com",
		}),
		fullName: withSwagger(z.string().min(1), {
			description: "Senior full legal name.",
			example: "Antonio Silva",
		}),
		nickname: withSwagger(z.string().min(1).optional(), {
			description: "Preferred display name for the senior.",
			example: "Toni",
		}),
		birthDate: withSwagger(z.coerce.date().optional(), {
			description: "Senior birth date. If omitted stored as null.",
			example: "1948-05-20T00:00:00.000Z",
		}),
		initialContext: withSwagger(z.string().min(1).max(2000).optional(), {
			description:
				"Optional free-form context to store as a pinned Compy note for the senior.",
			example:
				"Gosta de falar da aldeia e prefere evitar conversas sobre doença.",
		}),
	}),
	{
		description:
			"Payload used to create or update a senior onboarding profile.",
	},
);

export const updateSeniorLikesRequestSchema = withSwagger(
	z.object({
		likes: likesSchema,
	}),
	{
		description: "Update payload for senior likes and interests.",
	},
);

export const onboardSeniorResponseSchema = withSwagger(
	z.object({
		seniorId: withSwagger(z.string().min(1), {
			description: "Created or updated senior user identifier.",
			example: "usr_senior_123",
		}),
		accessCode: withSwagger(z.string().min(1), {
			description: "Access code assigned to the senior account.",
			example: "ABCD-EFGH-IJKL",
		}),
	}),
	{
		description: "Result of onboarding a senior.",
	},
);

export const assignSeniorRequestSchema = withSwagger(
	z.object({
		accessCode: withSwagger(z.string().min(1), {
			description: "Senior access code used to join a caregiver location.",
			example: "ABCD-EFGH-IJKL",
		}),
	}),
	{
		description: "Associate a senior account with the caregiver location.",
	},
);

export const assignSeniorResponseSchema = withSwagger(
	z.object({
		success: withSwagger(z.boolean(), {
			description: "Whether the association was completed.",
			example: true,
		}),
	}),
	{
		description: "Assignment result.",
	},
);

export const approveLocationRequestSchema = withSwagger(
	z.object({
		approved: withSwagger(z.boolean(), {
			description:
				"Whether the senior approved the pending location assignment.",
			example: true,
		}),
	}),
	{
		description: "Senior decision for a pending location association.",
	},
);

export const approveLocationResponseSchema = withSwagger(
	z.object({
		success: withSwagger(z.boolean(), {
			description: "Whether the approval action was processed.",
			example: true,
		}),
	}),
	{
		description: "Approval result.",
	},
);

export const onboardingStatusResponseSchema = withSwagger(
	z.object({
		locationApproved: withSwagger(z.boolean(), {
			description:
				"Whether the senior is currently linked to a caregiver location.",
			example: true,
		}),
		locationId: withSwagger(z.string().nullable(), {
			description: "Current linked location id, if any.",
			example: "loc_123",
		}),
		caregiverName: withSwagger(z.string(), {
			description: "Name of the caregiver responsible for the location.",
			example: "Maria Ferreira",
		}),
	}),
	{
		description:
			"Current onboarding and location association status for a senior.",
	},
);

export type OnboardSeniorRequest = z.infer<typeof onboardSeniorRequestSchema>;
export type OnboardSeniorResponse = z.infer<typeof onboardSeniorResponseSchema>;
export type AssignSeniorRequest = z.infer<typeof assignSeniorRequestSchema>;
export type AssignSeniorResponse = z.infer<typeof assignSeniorResponseSchema>;
export type ApproveLocationRequest = z.infer<
	typeof approveLocationRequestSchema
>;
export type ApproveLocationResponse = z.infer<
	typeof approveLocationResponseSchema
>;
export type OnboardingStatusResponse = z.infer<
	typeof onboardingStatusResponseSchema
>;
export type UpdateSeniorLikesRequest = z.infer<
	typeof updateSeniorLikesRequestSchema
>;
export type SeniorLikes = z.infer<typeof likesSchema>;
